CITY_AREAS["islamabad-islamabad"] = CITY_AREAS["islamabad-capital-territory-islamabad"];

function uniqueAreas(defs: AreaDef[]): AreaDef[] {
  const seen = new Set<string>();
  const out: AreaDef[] = [];
  for (const def of defs) {
    const key = slugify(def.name);
    if (!key || seen.has(key)) continue;
    seen.add(key);
    out.push(def);
  }
  return out;
}

function overlayForDistrict(district: FlatDistrict): AreaDef[] | undefined {
  if (CITY_AREAS[district.id]) return CITY_AREAS[district.id];
  const compact = `islamabad-${district.slug}`;
  if (district.slug === "islamabad" && CITY_AREAS[compact]) return CITY_AREAS[compact];
  return undefined;
}

export function flattenAreas(
  districts: FlatDistrict[] = flattenLocations().districts,
  tehsils: FlatTehsil[] = flattenLocations().tehsils,
): FlatArea[] {
  const areas: FlatArea[] = [];
  for (const district of districts) {
    const overlay = overlayForDistrict(district);
    const fallback = tehsils
      .filter((t) => t.districtId === district.id)
      .map((t) => ({ name: t.name } satisfies AreaDef));
    const defs = uniqueAreas([...(overlay ?? []), ...fallback]);
    if (defs.length === 0) defs.push({ name: district.name });
    for (const def of defs) {
      const slug = slugify(def.name);
      areas.push({
        id: `${district.id}-${slug}`,
        districtId: district.id,
        slug,
        name: def.name,
        aliases: (def.aliases ?? []).join("|"),
      });
    }
  }
  return areas;
}
